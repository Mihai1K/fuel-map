# Генератор семантического ядра «Тут Бензин».
# Комбинаторика: интенты × топливо × бренды × города (из OSM) × трассы.
# Частотность Wordstat подключается вторым проходом (нужен API-токен
# владельца) — колонка wordstat в CSV пока пустая.
#
# Запуск: python3 scripts/semantic-core.py "<папка вывода>"
import csv
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = sys.argv[1] if len(sys.argv) > 1 else HERE
os.makedirs(OUT_DIR, exist_ok=True)

cities = json.load(open(os.path.join(HERE, 'data', 'ru-cities.json')))

# Города дефицита — приоритет ×3 (лето 2026: Крым, юг)
HOT_REGions_HINT = [
    'Симферополь', 'Севастополь', 'Керчь', 'Евпатория', 'Ялта', 'Феодосия',
    'Джанкой', 'Алушта', 'Саки', 'Армянск', 'Краснодар', 'Сочи', 'Новороссийск',
    'Анапа', 'Геленджик', 'Туапсе', 'Армавир', 'Ейск', 'Ростов-на-Дону',
    'Таганрог', 'Шахты', 'Волгодонск', 'Астрахань', 'Элиста', 'Ставрополь',
    'Пятигорск', 'Кисловодск', 'Майкоп', 'Воронеж', 'Белгород', 'Курск',
]
HOT = set(HOT_REGions_HINT)

# — интенты с шаблонами; {c} — город в предложном/именительном (упрощаем
#   именительным: так и ищут — «где есть бензин краснодар»)
GEO_PATTERNS = [
    ('поиск топлива', 'где есть бензин {c}', 3.0),
    ('поиск топлива', 'где заправиться {c}', 2.6),
    ('поиск топлива', 'на какой заправке есть бензин {c}', 2.8),
    ('поиск топлива', 'бензин {c} сейчас', 2.6),
    ('поиск топлива', 'какие заправки работают {c}', 2.4),
    ('виды топлива', 'где есть 95 {c}', 2.5),
    ('виды топлива', 'где есть 92 {c}', 2.4),
    ('виды топлива', 'где есть дизель {c}', 2.4),
    ('виды топлива', 'где есть газ на заправке {c}', 1.8),
    ('проблемы', 'нет бензина {c}', 2.2),
    ('проблемы', 'очереди на заправках {c}', 2.2),
    ('проблемы', 'лимит бензина {c}', 2.0),
    ('проблемы', 'когда завезут бензин {c}', 2.0),
    ('проблемы', 'бензин по талонам {c}', 1.6),
    ('проблемы', 'бензин по номерам {c}', 1.6),
]

# Общероссийские (без города)
GENERIC = [
    ('поиск топлива', 'где есть бензин', 3.0),
    ('поиск топлива', 'карта заправок с бензином', 2.8),
    ('поиск топлива', 'карта где есть бензин', 2.8),
    ('поиск топлива', 'на какой заправке есть бензин', 2.8),
    ('поиск топлива', 'приложение где есть бензин', 2.6),
    ('конкуренты', 'гдебенз', 3.0),
    ('конкуренты', 'где бенз', 3.0),
    ('конкуренты', 'гдебенз карта', 2.8),
    ('конкуренты', 'карта бензина', 2.6),
    ('конкуренты', 'бензин сейчас карта', 2.6),
    ('виды топлива', 'где есть 95', 2.6),
    ('виды топлива', 'где есть 92', 2.5),
    ('виды топлива', 'где есть 98', 1.8),
    ('виды топлива', 'где есть 100 бензин', 1.6),
    ('виды топлива', 'где есть дизель', 2.4),
    ('проблемы', 'почему нет бензина', 2.2),
    ('проблемы', 'дефицит бензина 2026', 2.2),
    ('проблемы', 'очереди на азс', 2.0),
    ('проблемы', 'сколько литров дают на заправке', 1.8),
]

BRANDS = [
    'лукойл', 'роснефть', 'газпромнефть', 'газпром', 'татнефть',
    'башнефть', 'тебойл', 'teboil', 'нефтьмагистраль', 'атан', 'тес',
    'иркутскнефтепродукт', 'нк альянс', 'сургутнефтегаз',
]
BRAND_PATTERNS = [
    ('бренды', '{b} есть бензин', 2.0),
    ('бренды', '{b} бензин сейчас', 1.8),
    ('бренды', '{b} очередь', 1.6),
    ('бренды', '{b} работает', 1.6),
    ('бренды', '{b} карта заправок', 1.8),
]
# бренды × топ-города
BRAND_GEO_TOP = 60
BRAND_GEO_PATTERNS = [
    ('бренды', '{b} {c}', 1.4),
    ('бренды', '{b} бензин {c}', 1.7),
]

HIGHWAYS = [
    ('м4', 'М-4 «Дон»'), ('м5', 'М-5 «Урал»'), ('м7', 'М-7 «Волга»'),
    ('м8', 'М-8 «Холмогоры»'), ('м10', 'М-10 «Россия»'), ('м11', 'М-11 «Нева»'),
    ('м12', 'М-12 «Восток»'), ('р217', 'Р-217 «Кавказ»'), ('а290', 'А-290 (Крымский мост)'),
    ('таврида', 'А-291 «Таврида»'),
]
HIGHWAY_PATTERNS = [
    ('трассы', 'заправки на трассе {h}', 2.4),
    ('трассы', 'где есть бензин трасса {h}', 2.6),
    ('трассы', 'бензин на {h} сейчас', 2.2),
    ('трассы', 'очереди на заправках {h}', 2.0),
]

rows = []

def add(cluster, query, base, city='', pop=0):
    hot = 3.0 if city in HOT else 1.0
    pop_w = min(pop / 1_000_000, 1.5) if pop else 0.8
    score = round(base * hot * (0.5 + pop_w), 2)
    rows.append({
        'запрос': query.lower(), 'кластер': cluster, 'город': city,
        'население': pop or '', 'приоритет': score, 'wordstat': '',
    })

for cl, q, w in GENERIC:
    add(cl, q, w)

for c in cities:
    if c['pop'] < 10_000:
        continue
    for cl, tpl, w in GEO_PATTERNS:
        # мелким городам — только самые горячие шаблоны
        if c['pop'] < 50_000 and w < 2.4:
            continue
        add(cl, tpl.format(c=c['name']), w, c['name'], c['pop'])

for b in BRANDS:
    for cl, tpl, w in BRAND_PATTERNS:
        add(cl, tpl.format(b=b), w)

for c in cities[:BRAND_GEO_TOP]:
    for b in BRANDS[:8]:
        for cl, tpl, w in BRAND_GEO_PATTERNS:
            add(cl, tpl.format(b=b, c=c['name']), w, c['name'], c['pop'])

for code, full in HIGHWAYS:
    for cl, tpl, w in HIGHWAY_PATTERNS:
        add(cl, tpl.format(h=code), w)

# дедуп
seen = set()
uniq = []
for r in rows:
    if r['запрос'] in seen:
        continue
    seen.add(r['запрос'])
    uniq.append(r)
uniq.sort(key=lambda r: -r['приоритет'])

with open(os.path.join(OUT_DIR, 'ядро-полное.csv'), 'w', newline='') as f:
    w = csv.DictWriter(f, fieldnames=list(uniq[0].keys()))
    w.writeheader()
    w.writerows(uniq)

# сводка по кластерам
from collections import Counter, defaultdict
cnt = Counter(r['кластер'] for r in uniq)
top = defaultdict(list)
for r in uniq:
    if len(top[r['кластер']]) < 5:
        top[r['кластер']].append(r['запрос'])
with open(os.path.join(OUT_DIR, 'кластеры-сводка.csv'), 'w', newline='') as f:
    w = csv.writer(f)
    w.writerow(['кластер', 'запросов', 'примеры'])
    for cl, n in cnt.most_common():
        w.writerow([cl, n, ' | '.join(top[cl])])

print(f'ядро: {len(uniq)} запросов')
for cl, n in cnt.most_common():
    print(f'  {cl}: {n}')
