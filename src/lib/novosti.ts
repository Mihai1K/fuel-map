export function listNovosti(): NovostiArticle[] {
  return [...NOVOSTI].sort((a, b) => (a.publishedAt < b.publishedAt ? 1 : -1));
}

export function getNovosti(slug: string): NovostiArticle | undefined {
  return NOVOSTI.find((n) => n.slug === slug);
}

export function listNovostiByCity(citySlug: string): NovostiArticle[] {
  return listNovosti().filter((n) => n.citySlug === citySlug);
}
