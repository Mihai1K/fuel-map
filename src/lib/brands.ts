// Один бренд приезжает из OSM под несколькими написаниями. Чинить это
// в импортёре означало бы переимпорт 26 тыс. строк, поэтому нормализуем
// на чтении — дёшево и обратимо.
const ALIASES: Record<string, string> = {
  'Газпром Нефть': 'Газпромнефть',
  'Газпром нефть': 'Газпромнефть',
  'ООО Газпром газомоторное топливо': 'Газпром',
  'Газпром газомоторное топливо': 'Газпром',
  'Сибнефть': 'Газпромнефть', // историческое название сети
  'ТАИФ': 'ТАИФ-НК',
};

// «Independent», «АЗС», «АГЗС» и юрлица вида «ООО …» приезжают из OSM
// в поле brand, но брендом не являются — знак им не рисуем.
export function brandOf(network: string | null | undefined): Brand | null {
  if (!network) return null;
  const key = ALIASES[network] ?? network;
  return BRANDS[key] ?? null;
}

// Буквенный знак для «живого» пина: белый текст внутри тёмного корпуса.
export function brandGlyphHtml(network: string | null | undefined): string | null {
  const b = brandOf(network);
  if (!b) return null;
  // 10px — нижняя граница читаемости двухбуквенного знака в корпусе пина
  // (проверено в браузере 15.09.2026: на 9px «ГН» читается как «гн»)
  const size = b.mark.length > 1 ? 10 : 12;
  return (
    `<span style="display:block;color:#fff;font:800 ${size}px/1 ` +
    'Inter,system-ui,sans-serif;letter-spacing:-.02em;text-align:center">' +
    `${b.mark}</span>`
  );
}
