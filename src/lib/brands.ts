// внутри тёмного корпуса, а у станций без данных — светлым чипом, где
// статусного цвета нет вовсе.
//
// Таблица построена ОТ ДАННЫХ, а не от маппинга импортёра (правка
// 15.09.2026): первая версия была списана с BRAND_MAP в scripts/import-osm.ts,
